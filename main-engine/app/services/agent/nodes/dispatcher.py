import asyncio
import inspect
from typing import Any, Dict, List
from langchain_core.tools import BaseTool

from app.services.agent.state import AgentState, SubTask

# Concurrency throttle matching Neo4j pool constraints
MAX_CONCURRENT_TASKS = 2
_semaphore = asyncio.Semaphore(MAX_CONCURRENT_TASKS)


async def execute_task(task: SubTask, tool_map: Dict[str, BaseTool]) -> Dict[str, Any]:
    tool_entry = tool_map.get(task.tool)
    if not tool_entry:
        return {
            "task_id": task.task_id,
            "tool": task.tool,
            "success": False,
            "summary": f"Tool '{task.tool}' does not exist in registry.",
            "data": None,
        }

    async with _semaphore:
        try:
            target_fn = getattr(tool_entry, "coroutine", None) or getattr(
                tool_entry, "func", tool_entry
            )
            is_async = inspect.iscoroutinefunction(target_fn)

            if is_async:
                raw_result = await tool_entry.ainvoke(task.input_parameters)
            else:
                raw_result = await asyncio.to_thread(
                    tool_entry.invoke, task.input_parameters
                )

            preview = (
                str(raw_result)[:250] + "..."
                if len(str(raw_result)) > 250
                else str(raw_result)
            )

            return {
                "task_id": task.task_id,
                "tool": task.tool,
                "success": True,
                "summary": f"Executed {task.tool}({task.input_parameters}) -> {preview}",
                "data": raw_result,
            }
        except Exception as exc:
            return {
                "task_id": task.task_id,
                "tool": task.tool,
                "success": False,
                "summary": f"Error running {task.tool}: {str(exc)}",
                "data": None,
            }


async def tool_dispatcher_node(
    state: AgentState, tool_map: Dict[str, BaseTool]
) -> Dict[str, Any]:
    """
    Executes tasks generated by either the router's initial recipe
    or the orchestrator's discovery loop using the injected tool_map.
    """
    tasks: List[SubTask] = []

    # Priority 1: Check initial tasks from Router Recipe (Round 0)
    if state.get("loop_count", 0) == 0 and state.get("router_decision"):
        tasks = state["router_decision"].initial_tasks

    # Priority 2: Check tasks from Orchestrator Loop (Round 1+)
    elif state.get("orchestrator_decision"):
        tasks = state["orchestrator_decision"].next_tasks

    if not tasks:
        return {"gathered_context": []}

    coros = [execute_task(t, tool_map) for t in tasks]
    batch_results = await asyncio.gather(*coros)

    return {"gathered_context": batch_results}
